#include <iostream>
using namespace std;
int main()
{
    bool a = 3.14;
    int b = 3.14;
    float c = 3.14;
    double d = '3';
    char e = 97;
    cout << "bool   a=\t" << a << endl;
    cout << "int    b=\t" << b << endl;
    cout << "float  c=\t" << c << endl;
    cout << "double d=\t" << char(d) << endl;
    cout << "double e=\t" << int(e) << endl;
    return 0;
}
